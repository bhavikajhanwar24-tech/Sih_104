"""Markdown + JSON report writers for the evaluation harness (Context §15).

Reproducibility: seed, git commit, model IDs, and dataset versions are always recorded.
Honesty: numbers are written as measured — including high In-the-Wild EER (§3.1).
"""

from __future__ import annotations

import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional


def git_commit_hash(repo: Path) -> str:
    try:
        out = subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=str(repo),
            stderr=subprocess.DEVNULL,
            text=True,
        )
        return out.strip()
    except (subprocess.CalledProcessError, FileNotFoundError, OSError):
        return "unknown"


def _pct(x: Optional[float]) -> str:
    if x is None:
        return "—"
    return f"{100.0 * float(x):.2f}%"


def _num(x: Optional[float], digits: int = 4) -> str:
    if x is None:
        return "—"
    return f"{float(x):.{digits}f}"


def codec_comparison_rows(payload: dict[str, Any]) -> list[dict[str, Any]]:
    """Collapse cells into §15.3 before/after codec table rows."""
    by_cond: dict[str, dict[str, Any]] = {}
    for cell in payload.get("cells") or []:
        ch = cell.get("channel_condition") or "unknown"
        ds = cell.get("dataset_id") or ""
        # Prefer in-domain LA for codec rows; ITW is its own row (clean only).
        if ds == "in_the_wild":
            if ch != "clean_16k":
                continue
            key = "In-the-Wild"
        elif ds == "asvspoof2019_la_eval":
            key = {
                "clean_16k": "Clean 16 kHz",
                "opus_24k": "Opus 24 kbps",
                "g711_ulaw_8k": "G.711 µ-law 8 kHz",
                "amr_nb_12k2": "AMR-NB 12.2 kbps",
                "webrtc_wideband": "WebRTC wideband",
                "pstn_narrowband": "PSTN narrowband",
            }.get(ch, ch)
        else:
            continue
        row = by_cond.setdefault(
            key,
            {
                "condition": key,
                "eer_baseline": None,
                "eer_codec_aug": None,
                "min_tdcf_baseline": None,
                "min_tdcf_codec_aug": None,
            },
        )
        mid = str(cell.get("model_id") or "")
        eer = (cell.get("metrics") or {}).get("eer")
        tdcf = (cell.get("metrics") or {}).get("min_tdcf")
        if "codec_aug" in mid and "no_codec" not in mid:
            row["eer_codec_aug"] = eer
            row["min_tdcf_codec_aug"] = tdcf
        elif "baseline" in mid or "no_codec" in mid:
            row["eer_baseline"] = eer
            row["min_tdcf_baseline"] = tdcf
        else:
            # Single-model runs fill the codec-aug column.
            if row["eer_codec_aug"] is None:
                row["eer_codec_aug"] = eer
                row["min_tdcf_codec_aug"] = tdcf
    order = [
        "Clean 16 kHz",
        "Opus 24 kbps",
        "G.711 µ-law 8 kHz",
        "AMR-NB 12.2 kbps",
        "In-the-Wild",
    ]
    rows = [by_cond[k] for k in order if k in by_cond]
    for k, v in by_cond.items():
        if k not in order:
            rows.append(v)
    return rows


def write_results_json(payload: dict[str, Any], path: Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return path


def write_markdown_report(payload: dict[str, Any], path: Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    meta = payload.get("meta") or {}
    lines: list[str] = [
        "# SentinelVoice — Evaluation Report",
        "",
        "> Generated by `ml-engine/benchmarks/run_eval.py` (Context §15).",
        "> **Be honest:** In-the-Wild EER is expected to be far worse than in-domain (§3.1).",
        "> Acoustic evidence is only ~24% of fusion weight; architecture is designed around that fact.",
        "",
        "## Reproducibility",
        "",
        f"| Field | Value |",
        f"|---|---|",
        f"| Generated (UTC) | {meta.get('generated_at_utc', '—')} |",
        f"| Git commit | `{meta.get('git_commit', 'unknown')}` |",
        f"| Random seed | `{meta.get('seed', '—')}` |",
        f"| Harness version | `{meta.get('harness_version', '1')}` |",
        f"| Synthetic smoke | `{meta.get('synthetic', False)}` |",
        f"| Limit | `{meta.get('limit', 'none')}` |",
        "",
        "### Model checkpoints",
        "",
        "| Model ID | Checkpoint | Calibration |",
        "|---|---|---|",
    ]
    for m in payload.get("models") or []:
        lines.append(
            f"| `{m.get('model_id', '—')}` | `{m.get('checkpoint', '—')}` | `{m.get('calibration', '—')}` |"
        )
    lines += ["", "### Dataset versions", "", "| Dataset | Version | Source | N (primary) | Note |", "|---|---|---|---|---|"]
    for d in payload.get("datasets") or []:
        lines.append(
            f"| `{d.get('dataset_id')}` | `{d.get('version')}` | {d.get('source')} | "
            f"{d.get('n', '—')} | {d.get('note') or '—'} |"
        )

    lines += [
        "",
        "## Codec-degradation study (§15.3)",
        "",
        "Before/after codec-augmented training. Empty cells mean that checkpoint was not evaluated.",
        "",
        "| Condition | EER (baseline) | EER (codec-augmented) | min t-DCF (baseline) | min t-DCF (codec-aug) |",
        "|---|---|---|---|---|",
    ]
    for row in codec_comparison_rows(payload):
        lines.append(
            f"| {row['condition']} | {_pct(row.get('eer_baseline'))} | {_pct(row.get('eer_codec_aug'))} | "
            f"{_num(row.get('min_tdcf_baseline'))} | {_num(row.get('min_tdcf_codec_aug'))} |"
        )

    lines += [
        "",
        "## Full detection metrics (every dataset × channel × model)",
        "",
        "Scores: higher ⇒ more spoof-like. min t-DCF uses ASVspoof 2019 CM costs "
        "(Todisco et al., Interspeech 2019; C_miss=1, C_fa=10, π_spoof=0.05).",
        "",
        "| Model | Dataset | Channel | N | EER | EER θ | min t-DCF | AUC | "
        "FPR@TPR0.90 | ECE | Source |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for cell in payload.get("cells") or []:
        m = cell.get("metrics") or {}
        fpr90 = ((m.get("fpr_at_tpr") or {}).get("0.90") or {}).get("fpr")
        lines.append(
            f"| `{cell.get('model_id')}` | `{cell.get('dataset_id')}` | `{cell.get('channel_condition')}` | "
            f"{m.get('n', '—')} | {_pct(m.get('eer'))} | {_num(m.get('eer_threshold'), 4)} | "
            f"{_num(m.get('min_tdcf'))} | {_num(m.get('auc'))} | {_pct(fpr90)} | "
            f"{_num(m.get('ece'))} | {cell.get('source', '—')} |"
        )

    lines += [
        "",
        "## Fairness — false positive rate by group (§13.5)",
        "",
        "Metric: **FPR parity** at the model's EER threshold on the fairness probe set. "
        "A false positive means a legitimate customer is escalated.",
        "",
        "| Group | N bona | FPR | Notes |",
        "|---|---|---|---|",
    ]
    for g in (payload.get("fairness") or {}).get("groups") or []:
        lines.append(
            f"| `{g.get('group')}` | {g.get('n_bonafide', '—')} | {_pct(g.get('fpr'))} | {g.get('note') or '—'} |"
        )
    fair_note = (payload.get("fairness") or {}).get("note")
    if fair_note:
        lines += ["", f"> {fair_note}", ""]

    lat = payload.get("latency") or {}
    lines += [
        "",
        "## Latency (ms)",
        "",
        "Measured on the same host as the eval run. Fast path = antispoof window; "
        "slow path = ASR-sized stub when Whisper is unavailable; end-to-end = fast+slow.",
        "",
        "| Path | p50 | p95 | p99 | mean | n |",
        "|---|---|---|---|---|---|",
    ]
    for name in ("fast_path", "slow_path", "end_to_end"):
        block = lat.get(name) or {}
        lines.append(
            f"| {name} | {_num(block.get('p50_ms'), 2)} | {_num(block.get('p95_ms'), 2)} | "
            f"{_num(block.get('p99_ms'), 2)} | {_num(block.get('mean_ms'), 2)} | "
            f"{int(block.get('n', 0))} |"
        )

    plots = payload.get("plots") or []
    if plots:
        lines += ["", "## Reliability diagrams", ""]
        for p in plots:
            rel = Path(p).as_posix()
            # Prefer path relative to docs/ when under docs/
            lines.append(f"![{Path(p).stem}]({rel})")
            lines.append("")

    lines += [
        "",
        "## Honesty notes",
        "",
        "- If a cell used a **synthetic** corpus, it is labelled as such and must not be cited as a field result.",
        "- In-the-Wild EER in the mid-20s (%) is consistent with the literature collapse described in §3.1; "
        "do not paper over it.",
        "- Do not tune operating thresholds on the evaluation set — report EER / min t-DCF / FPR@TPR.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def build_meta(*, repo: Path, seed: int, synthetic: bool, limit: Optional[int]) -> dict[str, Any]:
    return {
        "generated_at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "git_commit": git_commit_hash(repo),
        "seed": seed,
        "harness_version": "1",
        "synthetic": synthetic,
        "limit": limit,
    }
